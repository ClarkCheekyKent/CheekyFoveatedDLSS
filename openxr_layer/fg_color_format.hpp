#pragma once
#include <dxgiformat.h>
namespace cheeky::fg {
inline bool srgb_color(DXGI_FORMAT f) noexcept {
    return f==DXGI_FORMAT_R8G8B8A8_UNORM_SRGB||f==DXGI_FORMAT_B8G8R8A8_UNORM_SRGB||f==DXGI_FORMAT_B8G8R8X8_UNORM_SRGB;
}
inline DXGI_FORMAT inference_color_format(DXGI_FORMAT f) noexcept {
    switch(f){
    case DXGI_FORMAT_R8G8B8A8_UNORM:case DXGI_FORMAT_R8G8B8A8_UNORM_SRGB:
    case DXGI_FORMAT_B8G8R8A8_UNORM:case DXGI_FORMAT_B8G8R8A8_UNORM_SRGB:
    case DXGI_FORMAT_B8G8R8X8_UNORM:case DXGI_FORMAT_B8G8R8X8_UNORM_SRGB:return DXGI_FORMAT_R8G8B8A8_UNORM;
    case DXGI_FORMAT_R10G10B10A2_UNORM:return f;
    default:return DXGI_FORMAT_R16G16B16A16_FLOAT;
    }
}
inline DXGI_FORMAT color_family(DXGI_FORMAT format) noexcept {
    switch(format) {
    case DXGI_FORMAT_R8G8B8A8_TYPELESS:case DXGI_FORMAT_R8G8B8A8_UNORM:case DXGI_FORMAT_R8G8B8A8_UNORM_SRGB:
    case DXGI_FORMAT_R8G8B8A8_UINT:case DXGI_FORMAT_R8G8B8A8_SNORM:case DXGI_FORMAT_R8G8B8A8_SINT:
        return DXGI_FORMAT_R8G8B8A8_TYPELESS;
    case DXGI_FORMAT_B8G8R8A8_TYPELESS:case DXGI_FORMAT_B8G8R8A8_UNORM:case DXGI_FORMAT_B8G8R8A8_UNORM_SRGB:
        return DXGI_FORMAT_B8G8R8A8_TYPELESS;
    case DXGI_FORMAT_B8G8R8X8_TYPELESS:case DXGI_FORMAT_B8G8R8X8_UNORM:case DXGI_FORMAT_B8G8R8X8_UNORM_SRGB:
        return DXGI_FORMAT_B8G8R8X8_TYPELESS;
    case DXGI_FORMAT_R16G16B16A16_TYPELESS:case DXGI_FORMAT_R16G16B16A16_FLOAT:case DXGI_FORMAT_R16G16B16A16_UNORM:
    case DXGI_FORMAT_R16G16B16A16_UINT:case DXGI_FORMAT_R16G16B16A16_SNORM:case DXGI_FORMAT_R16G16B16A16_SINT:
        return DXGI_FORMAT_R16G16B16A16_TYPELESS;
    case DXGI_FORMAT_R32G32B32A32_TYPELESS:case DXGI_FORMAT_R32G32B32A32_FLOAT:
    case DXGI_FORMAT_R32G32B32A32_UINT:case DXGI_FORMAT_R32G32B32A32_SINT:
        return DXGI_FORMAT_R32G32B32A32_TYPELESS;
    case DXGI_FORMAT_R10G10B10A2_TYPELESS:case DXGI_FORMAT_R10G10B10A2_UNORM:case DXGI_FORMAT_R10G10B10A2_UINT:
        return DXGI_FORMAT_R10G10B10A2_TYPELESS;
    default:return format;
    }
}
inline bool typeless_color(DXGI_FORMAT format) noexcept {
    return format==DXGI_FORMAT_R8G8B8A8_TYPELESS || format==DXGI_FORMAT_B8G8R8A8_TYPELESS ||
        format==DXGI_FORMAT_B8G8R8X8_TYPELESS || format==DXGI_FORMAT_R16G16B16A16_TYPELESS ||
        format==DXGI_FORMAT_R32G32B32A32_TYPELESS || format==DXGI_FORMAT_R10G10B10A2_TYPELESS;
}
inline bool compatible_color(DXGI_FORMAT a,DXGI_FORMAT b) noexcept {
    return a!=DXGI_FORMAT_UNKNOWN && b!=DXGI_FORMAT_UNKNOWN && color_family(a)==color_family(b);
}
inline bool writable_color(DXGI_FORMAT resource,DXGI_FORMAT view) noexcept {
    return resource==view||(typeless_color(resource)&&!typeless_color(view)&&compatible_color(resource,view));
}
inline DXGI_FORMAT capture_format(DXGI_FORMAT resource,DXGI_FORMAT declared) noexcept {
    if(declared==DXGI_FORMAT_UNKNOWN)return typeless_color(resource)?DXGI_FORMAT_UNKNOWN:resource;
    return !typeless_color(declared)&&compatible_color(resource,declared)?declared:DXGI_FORMAT_UNKNOWN;
}
}
